#!/usr/bin/env python3
"""Turns the syllabus outlines in this folder into SQL that loads subjects and
their topic trees.

    python3 crates/db/syllabus/generate.py > crates/db/migrations/NNNN_syllabus.sql

Outline format (one file per subject, under jss/ or sss/):

    subject: Biology
    level: sss
    syllabus: WAEC https://... unofficial
    syllabus: JAMB https://... official

    Theme [WJ]
      Topic [W]

Two spaces per level. The letters in brackets say which syllabuses list the
topic: W = WAEC, J = JAMB, N = NECO, R = NERDC.
"""

import json
import re
import sys
from pathlib import Path

BODIES = {"W": "WAEC", "J": "JAMB", "N": "NECO", "R": "NERDC"}
LINE = re.compile(r"^( *)(.+?) \[([A-Z]+)\]$")


def q(s: str) -> str:
    return "'" + s.replace("'", "''") + "'"


def parse(path: Path):
    head, topics = {}, []
    syllabuses = []
    stack = []  # (depth, node)
    for n, raw in enumerate(path.read_text().splitlines(), 1):
        if not raw.strip():
            continue
        if not stack and not raw.startswith(" ") and ": " in raw and "[" not in raw:
            key, value = raw.split(": ", 1)
            if key == "syllabus":
                body, url, kind = value.split()
                assert kind in ("official", "unofficial"), f"{path}:{n}: {kind}"
                syllabuses.append({"body": body, "url": url, "official": kind == "official"})
            else:
                head[key] = value
            continue
        m = LINE.match(raw)
        assert m, f"{path}:{n}: expected '<indent>Name [letters]'"
        indent, name, letters = m.groups()
        assert len(indent) % 2 == 0, f"{path}:{n}: indent by two spaces"
        depth = len(indent) // 2
        bodies = [BODIES[c] for c in letters]
        node = {"name": name.strip(), "bodies": bodies, "children": []}
        while stack and stack[-1][0] >= depth:
            stack.pop()
        if depth == 0:
            topics.append(node)
        else:
            assert stack and stack[-1][0] == depth - 1, f"{path}:{n}: indented too far"
            stack[-1][1]["children"].append(node)
        stack.append((depth, node))
    assert head.get("level") in ("jss", "sss"), f"{path}: level must be jss or sss"
    assert head.get("subject"), f"{path}: subject missing"
    return head["subject"], head["level"], syllabuses, topics


def main():
    root = Path(__file__).parent
    files = sorted(root.glob("*/*.txt"))
    out = [
        "-- Generated by crates/db/syllabus/generate.py from the outlines in",
        "-- crates/db/syllabus. Edit those and generate a new migration; don't edit this.",
        "",
    ]
    for path in files:
        subject, level, syllabuses, topics = parse(path)
        out.append(f"-- {path.relative_to(root)}")
        out.append(
            f"insert into subjects (level, name, syllabuses) values ({q(level)}, {q(subject)}, "
            f"{q(json.dumps(syllabuses))}::jsonb)\n"
            f"  on conflict (level, name) do update set syllabuses = excluded.syllabuses;"
        )

        def emit(nodes, parent_sql):
            for i, node in enumerate(nodes, 1):
                bodies = "array[" + ", ".join(q(b) for b in node["bodies"]) + "]"
                out.append(
                    "insert into syllabus_topics (subject_id, parent_id, name, position, bodies)\n"
                    f"  select s.id, {parent_sql}, {q(node['name'])}, {i}, {bodies}\n"
                    f"  from subjects s where s.level = {q(level)} and s.name = {q(subject)}\n"
                    "  on conflict (subject_id, parent_id, name) do update\n"
                    "    set position = excluded.position, bodies = excluded.bodies;"
                )
                if node["children"]:
                    child_parent = (
                        "(select t.id from syllabus_topics t join subjects s2 on s2.id = t.subject_id"
                        f" where s2.level = {q(level)} and s2.name = {q(subject)}"
                        f" and t.parent_id is not distinct from {parent_sql}"
                        f" and t.name = {q(node['name'])})"
                    )
                    emit(node["children"], child_parent)

        emit(topics, "null")
        out.append("")
    sys.stdout.write("\n".join(out))


if __name__ == "__main__":
    main()
